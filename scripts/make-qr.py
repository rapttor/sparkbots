#!/usr/bin/env python3
"""Regenerates src/shared/sponsorQr.ts: the QR code of the Ethereum receive address as an SVG path.
Needs the `qrencode` command line tool (brew install qrencode); nothing is fetched and the app has no QR dependency.
The result is verified by decoding it back (python3 + opencv-python, or `zbarimg`)."""
import re, subprocess, sys

ADDRESS = "0xeF4590e1c22Cabade5300aFa469f9dDEBA1275D2"   # must equal the address in src/shared/sponsor.ts
src = open("src/shared/sponsor.ts", encoding="utf8").read()
if ADDRESS not in src:
    sys.exit("the address in sponsor.ts differs from the one in this script")
out = subprocess.run(["qrencode", "-l", "M", "-m", "0", "-t", "ASCII", ADDRESS], capture_output=True, text=True, check=True).stdout
rows = [line for line in out.split("\n") if line.strip() != "" or line.startswith(" ")]
rows = [r for r in out.split("\n") if len(r) > 0]
mat = [[r[2 * i] == "#" for i in range(len(r) // 2)] for r in rows]
n = len(mat)
assert all(len(r) == n for r in mat), "not square"
# one horizontal run of dark modules = one rectangle segment in a single path
path = []
for y, row in enumerate(mat):
    x = 0
    while x < n:
        if row[x]:
            e = x
            while e < n and row[e]:
                e += 1
            path.append(f"M{x} {y}h{e - x}v1h-{e - x}z")
            x = e
        else:
            x += 1
rows_hex = ["".join("1" if c else "0" for c in r) for r in mat]
with open("src/shared/sponsorQr.ts", "w", encoding="utf8") as f:
    f.write("// Generated by scripts/make-qr.py from the Ethereum address in sponsor.ts (QR error correction M, no quiet zone). Do not edit by hand.\n")
    f.write(f"export const ETH_QR = {{ size: {n}, path: \"{''.join(path)}\" }};\n")
    f.write("/** The modules as rows of 0/1, for tests. */\n")
    f.write("export const ETH_QR_ROWS: readonly string[] = [\n" + "".join(f'  "{r}",\n' for r in rows_hex) + "];\n")
print("size", n, "path chars", len("".join(path)))
